import { describe, expect, it } from "vitest";
import { round1 } from "./rounding";

/** جدولِ مرجع، *از خودِ پایتون* گرفته شده:
 *
 *     [round(v, 1) for v in ...]
 *
 * شش ردیفِ اولِ این جدول همان‌هایی‌اند که `Math.round(v * 10) / 10` غلط
 * جواب می‌دهد — یعنی دقیقاً چیزی که پیش‌نمایشِ فرم را با سندِ رسمی مخالف
 * می‌کرد. اگر روزی `round1` به پیاده‌سازیِ ساده برگردد، این جدول قرمز
 * می‌شود.
 */
const PYTHON_ROUND_1: Array<[number, number]> = [
  [31.25, 31.2], // نیمِ دقیق → به زوج (ساده: ۳۱٫۳)
  [2.25, 2.2], //   نیمِ دقیق → به زوج (ساده: ۲٫۳)
  [0.25, 0.2], //   نیمِ دقیق → به زوج (ساده: ۰٫۳)
  [0.15, 0.1], //   نیمِ دقیق → به زوج (ساده: ۰٫۲)
  [56.55, 56.5], // نیمِ *ظاهری* روی یک درصدِ واقعی (ساده: ۵۶٫۶)

  // این یکی را `Math.round` هم درست می‌دهد، ولی این‌جاست چون نشان می‌دهد
  // ضربِ `v * 10` بی‌خطر نیست: خودِ ۰٫۱۴۵ کمی *زیرِ* نیم است و ضرب آن را
  // به `1.4500000000000002` می‌بَرد. هر پیاده‌سازی‌ای که مرز را روی حاصلِ
  // ضرب بسنجد، این‌جا می‌لغزد.
  [0.145, 0.1],

  [31.35, 31.4], // بالای نیم → بالا
  [2.35, 2.4],
  [0.05, 0.1],
  [87.65, 87.7],
  [99.95, 100.0],
  [12.34, 12.3],
  [33.333333333333336, 33.3],
  [66.66666666666667, 66.7],
  [44.0, 44.0],
  [100.0, 100.0],
  [0.0, 0.0],
];

describe("round1 — همان گِردکردنی که سرور می‌کند", () => {
  it.each(PYTHON_ROUND_1)("round1(%f) === %f", (input, expected) => {
    expect(round1(input)).toBe(expected);
  });

  it("نیمِ دقیق را به زوج می‌برد، نه همیشه بالا", () => {
    // جفتِ قرینه روی دو نیمِ *دقیقاً* نمایش‌پذیر: ۰٫۲۵ پایین می‌رود چون ۲ زوج
    // است، ۰٫۷۵ بالا می‌رود چون ۷ فرد است. «همیشه بالا» هر دو را بالا می‌برد.
    expect(round1(0.25)).toBe(0.2);
    expect(round1(0.75)).toBe(0.8);
  });

  it("منفی و نامتناهی را هم بی‌ایراد رد می‌کند", () => {
    expect(round1(-2.25)).toBe(-2.2);
    expect(round1(-2.35)).toBe(-2.4);
    expect(round1(Number.NaN)).toBeNaN();
    expect(round1(Number.POSITIVE_INFINITY)).toBe(Number.POSITIVE_INFINITY);
  });

  it("پیاده‌سازیِ سادهٔ قبلی روی همین جدول شکست می‌خورد", () => {
    // این تست *وجودِ* اختلاف را ثابت می‌کند. بی آن، ممکن بود جدول بالا را یک
    // `Math.round` هم سبز رد کند و تست چیزی را نسنجد.
    const naive = (v: number) => Math.round(v * 10) / 10;
    const differing = PYTHON_ROUND_1.filter(([input, expected]) => naive(input) !== expected).map(
      ([input]) => input,
    );
    expect(differing).toEqual([31.25, 2.25, 0.25, 0.15, 56.55]);
  });
});
