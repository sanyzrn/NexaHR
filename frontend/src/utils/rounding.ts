/** گِردکردن به یک رقم اعشار، دقیقاً همان‌طور که پایتون می‌کند.
 *
 * چرا یک فایل جدا برای یک تابع: پیش‌نمایشِ نمره در فرم و نمرهٔ روی سندِ رسمی
 * باید *یک* عدد باشند. نبودند.
 *
 * `Math.round(v * 10) / 10` نیم را همیشه بالا می‌برد، و پایتون `round(x, 1)`
 * نیمِ دقیق را به رقمِ زوج می‌بَرد (گِردکردنِ بانکداری). با وزن‌های
 * `[۳,۳,۳,۳,۲,۲]` و نمره‌های `[۱,۱,۲,۳,۱,۱]` نتیجهٔ واقعی ۳۱٫۲۵ می‌شود، پس
 * فرم ۳۱٫۳ نشان می‌داد و سند ۳۱٫۲ چاپ می‌کرد — روی همان پرونده، با همان
 * نمره‌ها. کارمندی که هر دو را می‌بیند، حق دارد فکر کند یکی‌شان دست‌کاری شده.
 *
 * سمتِ سرور عوض نمی‌شود: عدد روی سندِ هش‌شده می‌نشیند و تغییرش یعنی سندهای
 * گذشته با هشِ خودشان نخوانند. فرم است که باید با سرور هم‌شکل شود.
 *
 * ضربِ `v * 10` هم خودش خطای ممیز شناور می‌سازد و مرزِ نیم را جابه‌جا می‌کند
 * (`0.145 * 10` در جاوااسکریپت `1.4500000000000002` است، در حالی که خودِ
 * `0.145` کمی *زیرِ* یک‌ونیم‌دهم است و پایتون به ۰٫۱ گِردش می‌کند). پس
 * به‌جای ضرب، از بسطِ دهدهیِ خودِ همان double خوانده می‌شود.
 */
export function round1(value: number): number {
  if (!Number.isFinite(value)) return value;

  const negative = value < 0;
  // `toFixed(20)` طبق استاندارد، مقدارِ *واقعیِ* این double را تا ۲۰ رقم
  // درست گِرد می‌کند — و درصدهای این سامانه بین ۰ و ۱۰۰‌اند، پس ۲۰ رقم
  // بیش از اندازه کافی است تا مرزِ نیم قطعی تشخیص داده شود.
  const [intPart, fracPart = ""] = Math.abs(value).toFixed(20).split(".");

  const kept = fracPart.slice(0, 1) || "0";
  let scaled = Number(intPart) * 10 + Number(kept);

  // دنبالهٔ پس از رقمِ نگه‌داشته‌شده، بی صفرهای انتهایی. مقایسهٔ رشته‌ایِ
  // ارقام این‌جا درست است: «۴۹۹۹» از «۵» کوچک‌تر و «۵۰۰۰۱» از آن بزرگ‌تر.
  const tail = fracPart.slice(1).replace(/0+$/, "");
  if (tail === "5") {
    // نیمِ دقیق → به زوج، همان کاری که `round()` پایتون می‌کند.
    if (scaled % 2 !== 0) scaled += 1;
  } else if (tail > "5") {
    scaled += 1;
  }

  const result = scaled / 10;
  return negative ? -result : result;
}
