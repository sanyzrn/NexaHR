"""P1-08 — سرکوب کوهورت حداقلی در آمارهای تجمیعی.

یک «میانگین واحد» که روی دو نفر حساب شده، آمار گروه نیست — تقریباً همان امتیاز آن
دو نفر است. و اگر واحد یک نفر داشته باشد، دقیقاً امتیاز اوست، فقط با برچسب
«میانگین». هر عددی که *به‌نظر* بی‌نام می‌آید ولی روی جمعیت کوچکی حساب شده، در عمل
افشای فردی است.

قاعده‌ای که اعمال می‌شود:

* هر ردیفِ تفکیکی (به‌ازای واحد، شاخص، ارزیاب) با تعداد کمتر از آستانه، میانگینش
  خالی برمی‌گردد. تعداد خودش پنهان نمی‌شود؛ دانستن «این واحد ۲ ارزیابی دارد»
  افشای عملکرد نیست و صادقانه‌تر از حذف کامل ردیف است.
* آمار سرجمع فقط وقتی سرکوب می‌شود که کاربر صراحتاً یک فرد مشخص را فیلتر نکرده
  باشد — اگر خودش نام فرد را داده، چیزی «کشف» نمی‌شود.
* نماهای عمداً تک‌نفره (کارنامهٔ فرد، سری امتیازهای خودش) دست‌نخورده می‌مانند.

این تا وقتی آنالیتیکس فقط برای HR است بیشتر آینده‌نگری و محافظت از خروجی‌هایی است
که از دست HR خارج می‌شوند؛ ولی پیش‌نیاز سختِ باز کردن گزارش‌ها به نقش‌های دیگر است،
وگرنه تجمیع‌ها به یک دور زدنِ کنترل دسترسی تبدیل می‌شوند.
"""
from sqlalchemy import ColumnElement, distinct, func

from app.core.config import settings


def cohort_size(subject_personnel_id: ColumnElement) -> ColumnElement[int]:
    """شمارِ *نفرهای* یک ردیفِ تجمیعی — همان عددی که آستانه باید رویش بنشیند.

    `func.count()` شمارِ *ردیف* است و ردیف با نفر یکی نیست. قیدِ یکتای دیتابیس
    فقط پروندهٔ *باز* را محدود می‌کند
    (`uq_open_evaluation_per_personnel … WHERE status NOT IN ('finalized','cancelled')`)،
    پس هر نفر در هر دوره یک پروندهٔ نهایی‌شده روی هم جمع می‌کند.

    نتیجه‌اش این بود: واحدی با *یک* نفر که پنج دوره ارزیابی شده، `count=5`
    می‌داد، از آستانهٔ پنج رد می‌شد، و «میانگین واحد» منتشر می‌شد — عددی که
    میانگین گروه نبود، نمرهٔ همان یک نفر بود با برچسبِ گروهی. دقیقاً همان چیزی
    که این ماژول برای جلوگیری از آن نوشته شده.

    عددِ `count`ِ نمایشی سرِ جایش می‌ماند و همچنان «تعداد ارزیابی» است؛ فقط
    *سنجهٔ آستانه* از ردیف به نفر عوض می‌شود.
    """
    return func.count(distinct(subject_personnel_id))


def is_below_cohort(count: int) -> bool:
    return count < settings.min_cohort_size


def suppressed_avg(value: float | None, count: int) -> float | None:
    """میانگین را برمی‌گرداند، مگر این‌که جمعیتش کمتر از آستانه باشد."""
    if value is None or is_below_cohort(count):
        return None
    return value
