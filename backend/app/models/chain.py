#: عنوانِ منابع انسانی در سند. صندلیِ زنجیره نیست — مرحلهٔ داوریِ بی‌طرف است.
HR_LABEL = "منابع انسانی"


def hr_finalizes(
    unit_supervisor_user_id: int | None,
    deputy_user_id: int | None,
    hr_review_skipped: bool,
) -> bool:
    """در این پرونده، تأییدِ نهایی با منابع انسانی است و نه با مدیرعامل.

    فقط یک شکل: زنجیره‌ای که نه مسئولِ واحد دارد و نه معاونت، پس خودِ مدیرعامل
    نمره‌دهندهٔ اول است.

    چرا: تا امروز همان مدیرعامل تأییدکنندهٔ نهایی هم بود، و سند این را با یک
    جملهٔ افشا اعلام می‌کرد («نمره‌دهندهٔ اول و تأییدکنندهٔ نهایی یک نفر
    بوده‌اند»). افشا از کتمان بهتر است، ولی *تفکیکِ واقعیِ وظایف* از هر دو بهتر
    است: کسی که نمره داده، امضاکنندهٔ نهایی نباشد. منابع انسانی در این پرونده
    از قبل مرحلهٔ بررسی را دارد؛ حالا همان مرحله پرونده را می‌بندد.

    استثنا، و ناگزیر: پروندهٔ خودِ واحدِ منابع انسانی (`hr_review_skipped`)
    اصلاً مرحلهٔ HR ندارد، چون داورش هم‌تیمیِ موضوعِ پرونده می‌شد. آن‌جا کسی جز
    مدیرعامل نمانده و همان جملهٔ افشا سرِ جایش می‌ماند.
    """
    return (
        unit_supervisor_user_id is None
        and deputy_user_id is None
        and not hr_review_skipped
    )


def scorer_field(unit_supervisor_user_id: int | None, deputy_user_id: int | None) -> str:
    """کدام ستون، نمره‌دهندهٔ اول را نگه می‌دارد.

    زنجیره از *پایین* خالی می‌شود، پس اولین صندلیِ پرشده از پایین نمره‌دهنده
    است: مسئول واحد، وگرنه معاونت (مسیر «مدیر»)، وگرنه خودِ مدیرعامل (کسی که
    بالای سرش دیگر کسی نیست).

    دو نکته که این تابع را لازم می‌کنند:

    * هم روی *پرونده* کار می‌کند و هم روی *دسترسی* — چون هر دو همین دو ستون
      را دارند. پیش از این هر مصرف‌کننده نسخهٔ خودش را داشت و دو تای‌شان با
      `personnel.is_manager` تصمیم می‌گرفتند، پرچمی که قرار نیست شکلِ زنجیره
      را بگوید.
    * پاسخ هیچ‌وقت `None` نیست. مصرف‌کننده‌هایی که «مسئول واحد، وگرنه معاونت»
      می‌نوشتند برای زنجیرهٔ مستقیمِ مدیرعامل `None` می‌گرفتند و بی‌صدا
      می‌شکستند — یکی‌شان با NotNullViolation، وسط جاروی شبانه.
    """
    if unit_supervisor_user_id is not None:
        return "unit_supervisor_user_id"
    if deputy_user_id is not None:
        return "deputy_user_id"
    return "ceo_user_id"
