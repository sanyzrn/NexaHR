"""دفترِ راستی‌آزماییِ زنجیرهٔ ممیزی — و لنگری که از آن بیرون می‌آید (فازِ ۳پ).

مسئله
-----
`verify_chain` از ابتدای تاریخ حساب می‌کند. این برای درستی لازم است و برای
*هر بار باز کردنِ صفحهٔ گزارشِ رویدادها* گران: روی بیست‌وپنج هزار ردیف حدودِ
یک ثانیه، و آن عدد هرگز کوچک نمی‌شود چون زنجیره هیچ‌وقت کوتاه نمی‌شود.

راهِ حل و دامِ راهِ حل
----------------------
راهِ حل یک «لنگر» است: نقطه‌ای که تا آن‌جا قبلاً بررسی شده، تا بررسیِ تعاملی
فقط از آن‌جا به بعد را بسنجد.

دامش این است که لنگر خودش می‌تواند نقطهٔ کور شود. اگر لنگر بی بررسیِ کامل جلو
برود، دست‌بردن در ردیف‌های *پیش از* لنگر دیگر هرگز دیده نمی‌شود — و بدتر:
نشانِ سبزِ صفحه هم می‌گوید همه‌چیز سالم است. یعنی یک بهینه‌سازیِ ساده می‌تواند
تضمینِ اصلیِ این لاگ را بی‌صدا خراب کند.

پس قاعده یکی است و در `services/audit.record_full_verification` نوشته شده:
**لنگر فقط پس از یک راستی‌آزماییِ کاملِ موفق جلو می‌رود.** جاروی شبانه همان
بررسیِ کامل را می‌زند؛ هزینه‌اش از مسیرِ درخواست بیرون می‌رود، نه از سامانه.

چرا شکست‌ها هم این‌جا ثبت می‌شوند
----------------------------------
چون در غیرِ این صورت، همین بهینه‌سازی وضع را *بدتر* می‌کرد: بررسیِ سریع فقط
بعد از لنگر را می‌بیند، پس دست‌کاریِ پیش از لنگر در رابط نامرئی می‌شد و
صفحه سبز می‌ماند. با ثبتِ هر بررسی — سالم یا ناسالم — نشانِ صفحه می‌تواند
بگوید «آخرین بررسیِ کامل چه گفت و کِی بود»، و جارو هم به منابع انسانی اعلان
می‌دهد.

این جدول هم مثل خودِ لاگ append-only است (تریگرِ دیتابیس): دفتری که بشود
ویرایشش کرد، دفترِ راستی‌آزمایی نیست.
"""
from datetime import datetime

from sqlalchemy import Boolean, DateTime, ForeignKey, Index, Integer, String, func
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class AuditChainCheck(Base):
    __tablename__ = "audit_chain_checks"

    id: Mapped[int] = mapped_column(primary_key=True)

    #: نتیجهٔ همان بررسی. «لنگر» یعنی تازه‌ترین ردیفِ `ok = true`.
    ok: Mapped[bool] = mapped_column(Boolean, nullable=False)

    #: تا کدام ردیفِ لاگ بررسی شد. در بررسیِ ناموفق هم پر می‌شود (سرِ زنجیره در
    #: همان لحظه)، چون «تا کجا نگاه کردیم» جزوِ نتیجه است.
    #:
    #: کلیدِ خارجی دارد تا لنگر نتواند به ردیفی اشاره کند که وجود ندارد. روی
    #: جدولی که خودش append-only است این قید هیچ‌وقت فعال نمی‌شود — و همان
    #: «هیچ‌وقت» چیزی است که می‌خواهیم در ساختار نوشته باشد، نه در حافظهٔ کسی.
    #:
    #: یک اثرِ جانبیِ خوش‌آیند هم دارد: `TRUNCATE audit_log`ِ ساده حالا پیش از
    #: رسیدن به تریگرِ append-only، به همین کلیدِ خارجی می‌خورَد. پیامِ خطا
    #: عوض می‌شود ولی جواب همان «نه» است — و `tests/test_audit_chain.py`
    #: هر چهار راهِ ممکن را می‌سنجد، نه یک جمله را.
    log_id: Mapped[int | None] = mapped_column(ForeignKey("audit_log.id"), nullable=True)

    #: هشِ ردیفِ `log_id` در لحظهٔ بررسی.
    #:
    #: بی این، لنگر یک عددِ بی‌پشتوانه بود: هر کسی که به دیتابیس دست دارد
    #: می‌توانست `log_id` را روی سرِ زنجیره بگذارد و بررسیِ سریع عملاً هیچ ردیفی
    #: را نسنجد. با این، بررسیِ سریع اول می‌پرسد «آیا لنگر هنوز با خودِ لاگ
    #: می‌خوانَد؟» و اگر نه، همان‌جا اعلامِ شکست می‌کند.
    entry_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)

    #: چند ردیف واقعاً بازمحاسبه شد.
    verified_rows: Mapped[int] = mapped_column(Integer, nullable=False, default=0)

    #: نخستین ردیفِ ناسازگار و علتش — همان دو چیزی که `verify_chain` برمی‌گرداند.
    broken_at_id: Mapped[int | None] = mapped_column(Integer, nullable=True)
    reason: Mapped[str | None] = mapped_column(String(300), nullable=True)

    verified_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    # ایندکس این‌جا هم اعلام می‌شود و نه فقط در مایگریشن، وگرنه
    # `alembic revision --autogenerate` آن را «اضافی» می‌بیند و DROP پیشنهاد
    # می‌دهد — همان درسی که بقیهٔ مدل‌ها بالای `__table_args__`شان نوشته‌اند.
    #
    # هر دو خواندنِ داغ روی همین دو ستون است: «تازه‌ترین لنگر»
    # (`ok = true`, بزرگ‌ترین `id`) و «تازه‌ترین بررسی».
    __table_args__ = (Index("ix_audit_chain_checks_ok_id", "ok", "id"),)
