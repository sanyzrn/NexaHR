"""ارقامِ فارسی و تاریخِ شمسی — برای *هر* متنی که به کاربر می‌رسد.

تا امروز این‌ها در `services/pdf.py` بودند و فقط سندِ رسمی از آن‌ها استفاده
می‌کرد. نتیجه‌اش این بود که سامانه دو استانداردِ عددی داشت:

* سند و رابط، فارسی — «۱۴۰۴/۰۶/۱۵»، «۸۲٫۵٪».
* متن‌هایی که *سرور* می‌نویسد، لاتین — «قرارداد «کارمند مرزی» 3 روز دیگر به
  پایان می‌رسد»، «مهلت ثبت پروندهٔ EVL-… تا 2026-01-05 تمدید شد».

و بدترین جایش روی همان سندِ رسمی می‌نشست: کامنتِ تمدیدِ مهلت با تاریخِ میلادی
ثبت می‌شد، `snapshot` همهٔ کامنت‌ها را برمی‌داشت، و قالب آن را کنارِ تاریخ‌های
شمسیِ خودش چاپ می‌کرد.

این ماژول عمداً در `core` است و نه در `services`: متنِ اعلان و پیامِ خطا نباید
برای فارسی‌کردنِ یک عدد، ماژولِ PDF (و WeasyPrint) را وارد کند.

**کجا اعمال نشود:** کلیدِ یکتاییِ اعلان (`notify_once`)، مقادیرِ
`old_value`/`new_value` در لاگِ ممیزی، و هر رشته‌ای که قرار است دوباره
تجزیه شود. آن‌ها داده‌اند، نه متن.
"""
from datetime import date, datetime

import jdatetime

from app.core.clock import to_local

PERSIAN_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def fa_digits(value: object) -> str:
    """ارقامِ لاتینِ یک مقدار را فارسی می‌کند.

    نقطهٔ اعشار هم به جداکنندهٔ فارسی (U+066B) تبدیل می‌شود، چون «۸۲.۵» با
    نقطهٔ لاتین در متنِ راست‌به‌چپ جای درستی نمی‌نشیند.

    شناسه‌ها عمداً از این فیلتر رد نمی‌شوند: کدِ پرونده و کدِ پرسنلی و نامِ
    کاربری *برچسب*‌اند نه عدد، و باید همان‌طور که در سامانه جست‌وجو می‌شوند
    نوشته شوند.

    `None` به خطِ تیره می‌رود و نه به «None»: این تابع در قالبِ سند هم فیلتر
    است و آن‌جا مقدارِ خالی زیاد پیش می‌آید.
    """
    if value is None:
        return "—"
    return str(value).translate(PERSIAN_DIGITS).replace(".", "٫")


def fa_date(value: date | datetime | None) -> str:
    """تاریخِ شمسیِ *روز* با ارقامِ فارسی — برای متن، نه برای داده.

    قرینهٔ `pdf.to_jalali` است بی ساعت. `datetime` اول به وقتِ محلیِ سازمان
    می‌رود (`core/clock.to_local`) وگرنه رویدادِ ۱:۰۰ بامداد، *روزِ قبل* چاپ
    می‌شود؛ `date` ساده همان است که هست و انتقالی لازم ندارد.
    """
    if value is None:
        return "—"
    if isinstance(value, datetime):
        value = to_local(value).date()
    jalali = jdatetime.date.fromgregorian(date=value)
    return jalali.strftime("%Y/%m/%d").translate(PERSIAN_DIGITS)
