"""مرتب‌سازیِ متنِ فارسی در دیتابیس.

`ORDER BY` پیش‌فرضِ Postgres روی یک ستونِ متنی، ترتیبِ *بایت* می‌دهد. برای
فارسی این یعنی فهرستی که به‌نظرِ کاربر بی‌نظم است:

* «آ» (U+0622) و «ا» (U+0627) پنج کدنقطه فاصله دارند، پس «آرش» و «امیر» کنار
  هم نمی‌نشینند.
* و بدتر: دادهٔ واردشده از اکسل هر دو شکلِ `ی/ي` و `ک/ك` را دارد — کاربرِ
  ویندوز صفحه‌کلیدِ عربی داشته. «یوسفی» و «يوسفی» دو سرِ فهرست می‌افتند، در
  حالی که برای هر خواننده‌ای یک نام‌اند.

هر دو با یک عبارت حل می‌شوند و کارِ سنگین را Postgres می‌کند، نه پایتون:

* `translate` شکلِ عربیِ آن دو حرف را به فارسی می‌برد — فقط برای *مقایسه*؛
  مقدارِ ذخیره‌شده دست نمی‌خورد.
* `collate("fa-x-icu")` از collationهای ICU که در خودِ Postgres هست استفاده
  می‌کند. چیزی نصب نمی‌شود.
* `trim` فاصله‌های ابتدا و انتها را که از اکسل می‌آیند کنار می‌گذارد، وگرنه
  « احمدی» پیش از «آبادی» می‌نشیند.

فقط روی ستونِ *متنی*: تاریخ و عدد ترتیبِ طبیعیِ خودشان را دارند و بردنشان به
متن، «۱۴۰۴/۱۰/۰۱» را پیش از «۱۴۰۴/۹/۰۱» می‌گذارد.
"""
from sqlalchemy import func


def persian_text(column):
    """همان ستون، ولی با ترتیبی که یک فارسی‌زبان انتظار دارد."""
    return func.translate(func.trim(column), "يك", "یک").collate("fa-x-icu")
